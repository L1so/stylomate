<?php

namespace App\Services\Fashion\Mock;

use App\Services\Fashion\FashionException;
use App\Services\Fashion\Media;
use App\Services\Fashion\TryOnResults;
use Illuminate\Http\UploadedFile;

/**
 * Virtual Try-On versi MOCK = AI PALSU. Menempelkan gambar pakaian ke foto memakai PHP GD.
 * Hasil SENGAJA diberi tulisan "MOCK RESULT" supaya tidak disangka hasil AI sungguhan.
 * Uji jalur error: unggah foto yang NAMA FILE-nya mengandung kata "fail" (mis. fail.jpg).
 */
class MockTryOn
{
    /**
     * @param array $garment ['source','id','name','category','imageUrl']
     * @return array{id:string,imageUrl:string}
     */
    public function generate(UploadedFile $person, array $garment): array
    {
        usleep(2500000); // meniru AI yang lambat, supaya indikator loading bisa diuji

        if (preg_match('/fail/i', $person->getClientOriginalName())) {
            throw new FashionException('The AI service could not process this photo (simulated failure).', 502);
        }
        if (!extension_loaded('gd')) {
            throw new FashionException('The mock try-on needs the PHP GD extension. Enable extension=gd in php.ini.', 500);
        }

        $personImg = @imagecreatefromstring(file_get_contents($person->getRealPath()));
        $cloth = @imagecreatefromstring(Media::fromUrl($garment['imageUrl'])['body']);
        if ($personImg === false || $cloth === false) {
            throw new FashionException('The photo or the clothing image could not be read.', 422);
        }

        // Kanvas selebar 768 px (tinggi mengikuti rasio foto).
        $pw = imagesx($personImg);
        $ph = imagesy($personImg);
        $w = 768;
        $h = (int) round($w * $ph / $pw);
        $canvas = imagecreatetruecolor($w, $h);
        imagecopyresampled($canvas, $personImg, 0, 0, 0, 0, $w, $h, $pw, $ph);

        // Pakaian: lebar 50% kanvas, di tengah, mulai 20% dari atas (BUKAN hasil AI).
        $gw = (int) ($w * 0.5);
        $gh = (int) ($gw * imagesy($cloth) / imagesx($cloth));
        imagealphablending($canvas, true);
        imagecopyresampled($canvas, $cloth, (int) (($w - $gw) / 2), (int) ($h * 0.2), 0, 0, $gw, $gh, imagesx($cloth), imagesy($cloth));

        // Pita watermark di bawah.
        $text = 'MOCK RESULT - not generated by AI';
        imagefilledrectangle($canvas, 0, $h - 36, $w, $h, imagecolorallocatealpha($canvas, 0, 0, 0, 40));
        imagestring($canvas, 5, (int) (($w - strlen($text) * 9) / 2), $h - 28, $text, imagecolorallocate($canvas, 255, 255, 255));

        ob_start();
        imagejpeg($canvas, null, 85);
        $bytes = ob_get_clean();

        $stored = TryOnResults::put($bytes, 'jpg');
        return ['id' => $stored['file'], 'imageUrl' => $stored['url']];
    }

    /** Simpan permanen: salin hasil sementara ke folder mock dan catat di riwayat. */
    public function saveResult($id, array $garment): void
    {
        $source = is_string($id) ? TryOnResults::path($id) : null;
        if ($source === null) {
            throw new FashionException('This result is no longer available. Generate it again.', 404);
        }
        MockDb::ensureDirs();
        $db = MockDb::read();
        $file = 'tryon-' . $id;
        copy($source, MockDb::filesDir() . '/' . $file);
        $db['tryOnResults'][] = [
            'id'        => MockDb::nextId($db),
            'image'     => $file,
            'garment'   => ['source' => $garment['source'], 'id' => $garment['id'], 'name' => $garment['name']],
            'createdAt' => date('c'),
        ];
        MockDb::write($db);
    }

    public function listHistory(): array
    {
        $list = [];
        foreach (array_reverse(MockDb::read()['tryOnResults']) as $row) {
            $list[] = [
                'id'         => $row['id'],
                'imageUrl'   => MockDb::url($row['image']),
                'createdAt'  => $row['createdAt'],
                'garmentName' => $row['garment']['name'] ?? '',
            ];
        }
        return $list;
    }
}
