// Virtual Try-On versi MOCK: AI PALSU. Menempelkan gambar pakaian ke foto di canvas.
// Hasilnya SENGAJA diberi watermark "MOCK" supaya tidak disangka hasil AI sungguhan.
// Cara menguji error: unggah foto yang NAMA FILE-nya mengandung kata "fail" (mis. fail.jpg).
import { readDb, writeDb, nextId, delay } from './db.js'
import { ApiError } from '../errors.js'
import { loadImage } from '../../../features/fashion/utils/image.js'

export async function generateTryOn({ personFile, garment }) {
  await delay(2500) // meniru AI yang lambat, supaya loading indicator bisa diuji
  if (/fail/i.test(personFile.name)) {
    throw new ApiError('The AI service could not process this photo (simulated failure).', 502)
  }

  const personUrl = URL.createObjectURL(personFile)
  try {
    const [person, cloth] = await Promise.all([loadImage(personUrl), loadImage(garment.imageUrl)])
    const W = 768
    const H = Math.round((W * person.naturalHeight) / person.naturalWidth)
    const canvas = document.createElement('canvas')
    canvas.width = W
    canvas.height = H
    const ctx = canvas.getContext('2d')

    ctx.drawImage(person, 0, 0, W, H)
    const gw = W * 0.5 // pakaian ditaruh kira-kira di area dada (bukan hasil AI!)
    const gh = (gw * cloth.naturalHeight) / cloth.naturalWidth
    ctx.globalAlpha = 0.92
    ctx.drawImage(cloth, (W - gw) / 2, H * 0.2, gw, gh)
    ctx.globalAlpha = 1

    ctx.fillStyle = 'rgba(0,0,0,0.7)'
    ctx.fillRect(0, H - 36, W, 36)
    ctx.fillStyle = '#fff'
    ctx.font = 'bold 16px monospace'
    ctx.textAlign = 'center'
    ctx.fillText('MOCK RESULT - not generated by AI', W / 2, H - 13)

    return { id: `mock-${Date.now()}`, imageUrl: canvas.toDataURL('image/jpeg', 0.85) }
  } catch (err) {
    if (err?.name === 'SecurityError') {
      throw new ApiError('The try-on mock cannot read images from another origin (CORS). Use mock data as well, or turn the try-on mock off.')
    }
    throw err
  } finally {
    URL.revokeObjectURL(personUrl)
  }
}

export async function saveResult({ imageUrl, garment }) {
  await delay(300)
  const db = readDb()
  db.tryOnResults.push({
    id: nextId(db),
    imageUrl,
    garment: { source: garment.source, id: garment.id, name: garment.name },
    createdAt: new Date().toISOString(),
  })
  writeDb(db)
}

export async function listHistory() {
  await delay(250)
  return [...readDb().tryOnResults].reverse()
}
